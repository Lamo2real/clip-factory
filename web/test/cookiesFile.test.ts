// The cookies.txt check before upload (docs/CONTRACTS.md §29.6).
import { describe, expect, it } from "vitest";
import { checkCookies, COOKIES_STEPS, COOKIES_WORDS } from "../src/lib/cookiesFile.ts";

const NOW = 1_795_000_000;
const row = (domain: string, name: string, expires: number) => [domain, "TRUE", "/", "TRUE", String(expires), name, "x"].join("\t");
const HEAD = "# Netscape HTTP Cookie File\n# This file is generated by Get cookies.txt LOCALLY. Do not edit.\n";

describe("checkCookies", () => {
  it("accepts a signed-in YouTube export", () => {
    const text = HEAD + [row(".youtube.com", "PREF", NOW + 99), row(".youtube.com", "LOGIN_INFO", NOW + 9999)].join("\n");
    expect(checkCookies(text, NOW)).toBe("ok");
  });

  it("reads #HttpOnly_ lines and CRLF line endings", () => {
    const text = HEAD.replace(/\n/g, "\r\n") + `#HttpOnly_${row(".youtube.com", "__Secure-3PSID", NOW + 50)}\r\n`;
    expect(checkCookies(text, NOW)).toBe("ok");
  });

  it("counts a session cookie (expiry 0) as fresh", () => {
    expect(checkCookies(row("www.youtube.com", "SAPISID", 0), NOW)).toBe("ok");
  });

  it("says when the file is not cookies.txt", () => {
    expect(checkCookies("", NOW)).toBe("notCookies");
    expect(checkCookies("   \n\n", NOW)).toBe("notCookies");
    expect(checkCookies(HEAD, NOW)).toBe("notCookies");
    expect(checkCookies('{"cookies": []}', NOW)).toBe("notCookies");
    expect(checkCookies("a b c d e f g", NOW)).toBe("notCookies");
  });

  it("says when there is no YouTube sign-in", () => {
    expect(checkCookies(HEAD + row(".youtube.com", "PREF", NOW + 99), NOW)).toBe("notSignedIn");
    expect(checkCookies(HEAD + row(".google.com", "SAPISID", NOW + 99), NOW)).toBe("notSignedIn");
    expect(checkCookies(HEAD + row(".notyoutube.com", "SAPISID", NOW + 99), NOW)).toBe("notSignedIn");
  });

  it("says when the sign-in ran out", () => {
    const text = HEAD + [row(".youtube.com", "LOGIN_INFO", NOW - 1), row(".youtube.com", "SAPISID", NOW - 100)].join("\n");
    expect(checkCookies(text, NOW)).toBe("expired");
  });

  it("uses plain words", () => {
    for (const t of [...Object.values(COOKIES_WORDS), ...COOKIES_STEPS]) {
      expect(t.length).toBeLessThanOrEqual(110);
      expect(t).not.toMatch(/Netscape|LOGIN_INFO|SAPISID|session|token/i);
    }
    expect(COOKIES_STEPS.join(" ")).toMatch(/private window/);
    expect(COOKIES_STEPS.at(-2)).toMatch(/^Close the private window/);
  });
});
