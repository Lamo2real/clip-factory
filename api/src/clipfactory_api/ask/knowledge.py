"""The always-included app knowledge of Ask (docs/CONTRACTS.md §27.2).

``knowledge.json`` and ``library/*.md`` are generated by ``web/scripts/ask-knowledge.mjs`` from the help corpus, the
owner docs, the settings tree and the library of project docs, already passed through the secrets filter. They are
committed and ship in the Lambda zip as package data. The text is byte-stable for one version, so the system prompt
built from it is a stable cache prefix.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
PACK = HERE / "knowledge.json"
LIBRARY = HERE / "library"
MAX_DOC_CHARS = 30_000
LIBRARY_ID = re.compile(r"^[a-z0-9][a-z0-9-]{0,80}$")


class KnowledgeError(Exception):
    """The pack is missing or broken (the build and the tests catch this first)."""


@dataclass(frozen=True)
class LibraryEntry:
    id: str
    title: str
    line: str
    chars: int


@dataclass(frozen=True)
class Action:
    id: str
    label: str
    to: str
    highlight: tuple[str, ...] = ()

    def public(self) -> dict[str, Any]:
        out: dict[str, Any] = {"id": self.id, "label": self.label, "to": self.to}
        if self.highlight:
            out["highlight"] = list(self.highlight)
        return out


@dataclass(frozen=True)
class Knowledge:
    version: str
    text: str  # the system block: every part, in order
    library: tuple[LibraryEntry, ...]
    actions: dict[str, Action]  # the only buttons Ask may show (from the app map)

    def entry(self, doc_id: str) -> LibraryEntry | None:
        return next((e for e in self.library if e.id == doc_id), None)


def parse(raw: Any) -> Knowledge:
    if not isinstance(raw, dict) or not isinstance(raw.get("version"), str) or not isinstance(raw.get("parts"), list):
        raise KnowledgeError("not a knowledge pack")
    parts = []
    for part in raw["parts"]:
        if not isinstance(part, dict) or not all(isinstance(part.get(k), str) for k in ("id", "title", "text")):
            raise KnowledgeError("bad part")
        parts.append(f'<knowledge part="{part["id"]}" title="{part["title"]}">\n{part["text"]}\n</knowledge>')
    library = []
    for row in raw.get("library") or []:
        if not isinstance(row, dict) or not LIBRARY_ID.match(str(row.get("id") or "")):
            raise KnowledgeError("bad library row")
        library.append(
            LibraryEntry(
                str(row["id"]), str(row.get("title") or ""), str(row.get("line") or ""), int(row.get("chars") or 0)
            )
        )
    index = "\n".join(f"{e.id} · {e.title} · {e.line}" for e in library)
    parts.append(
        '<knowledge part="library" title="Library index (read a section with read_app_doc)">\n'
        + index
        + "\n</knowledge>"
    )
    actions = {}
    for a in raw.get("actions") or []:
        if isinstance(a, dict) and all(isinstance(a.get(k), str) for k in ("id", "label", "to")):
            light = tuple(str(h) for h in a.get("highlight") or [] if isinstance(h, str))
            actions[a["id"]] = Action(a["id"], a["label"], a["to"], light)
    text = f'<clip_factory_knowledge version="{raw["version"]}">\n' + "\n\n".join(parts) + "\n</clip_factory_knowledge>"
    return Knowledge(raw["version"], text, tuple(library), actions)


@cache
def load(path: Path = PACK) -> Knowledge:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise KnowledgeError(type(e).__name__) from e
    return parse(raw)


def read_section(doc_id: str, knowledge: Knowledge, library_dir: Path = LIBRARY) -> str | None:
    """One library section (≤ 30,000 characters), or None for an id that is not in the index."""
    if not LIBRARY_ID.match(doc_id) or knowledge.entry(doc_id) is None:
        return None
    path = library_dir / f"{doc_id}.md"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    return text[:MAX_DOC_CHARS]
